const LANG_STORAGE_KEY = "app_lang";
function getLang() {
  return localStorage.getItem(LANG_STORAGE_KEY) || "vi";
}

/* t(key, vars) — dùng cho cả text tĩnh và app.js.
   Nếu thiếu key ở ngôn ngữ hiện tại, fallback về "vi", rồi về chính key. */
function tr(key, vars) {
  const lang = getLang();
  let str = (I18N[lang] && I18N[lang][key]) || I18N.vi[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      str = str.split(`{{${k}}}`).join(vars[k]);
    });
  }
  return str;
}

function applyI18n() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.title = tr("app.title");

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.textContent = tr(key);
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    el.innerHTML = tr(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = tr(key);
  });
  document.querySelectorAll("[data-i18n-value]").forEach(el => {
    const key = el.getAttribute("data-i18n-value");
    el.textContent = tr(key);
  });

  document.querySelectorAll(".lang-switch [data-lang]").forEach(btn => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });
}

function setLang(lang) {
  if (!I18N[lang]) return;
  localStorage.setItem(LANG_STORAGE_KEY, lang);
  applyI18n();
  // Re-render các phần nội dung động nếu app.js đã nạp xong các hàm này
  try { if (typeof renderAll === "function") renderAll(); } catch (e) {}
  try { if (typeof renderUserList === "function") renderUserList(); } catch (e) {}
  try { if (typeof populateTypeSelect === "function") populateTypeSelect(); } catch (e) {}
  try { if (typeof updateRoleBadge === "function") updateRoleBadge(); } catch (e) {}
}

document.addEventListener("DOMContentLoaded", applyI18n);

document.addEventListener("click", e => {
  const btn = e.target.closest("[data-lang]");
  if (btn) setLang(btn.getAttribute("data-lang"));
});
